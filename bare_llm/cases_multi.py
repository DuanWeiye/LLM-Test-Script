#!/usr/bin/env python3
"""多轮一致性卷（MT1~MT4）。2026-09-06 新增。

**为什么加这个维度**：改版前的裸卷 100% 是单轮题 —— 一问一答，问完就结束。
可真实使用几乎全是长对话，而长对话里最常翻车的恰恰是这四件事：

  MT1  早先定的**格式约定**，聊了几轮、话题岔开又绕回来之后，还守不守
  MT2  早先说过的**事实**，在混入相似干扰项之后，还记不记得准
  MT3  中途**改了主意**，模型跟不跟得上（还是死抱着第一条指令）
  MT4  早先立的**硬约束**，在用户催「更简短」时会不会被顺手丢掉

这些单轮题一个都测不到，agent 卷也测不到（那边是一次性任务）。

题目形态刻意贴近主人的真实使用场景（设备调试、写脚本），不是 `a==a` 那种玩具题。
设备编号与故障都是虚构的，跟 agent 卷的 gw7_field 没有关系，别混着看。

格式：(id, lang, turns, grade)   —— turns 是按顺序发出的 user 消息列表，
grade 收整轮响应列表，返回 (bool, info)。
"""
import re

# 判分辅助 ---------------------------------------------------------------

def _last(rs):
    return (rs[-1].get("content") or "") if rs else ""


def _codes(rs):
    """把每一轮回复里的代码块抠出来。**只认围栏内的内容**。

    ⚠ 这里踩过一个坑，值得记下来：最初的版本在匹配不到围栏时「退化成整段文本当代码」，
      结果模型在正文里写「不要用 `eval()`，有注入风险」也被判成违反约束 —— 把一个
      完全正确的回答判成了零分。散文不是代码，没写代码就不存在违不违反写码约束。

    另一半原因是**截断**：`max_tokens` 不够时结尾的 ``` 根本不会输出，围栏永远不闭合，
    于是每次截断都触发上面那个退化分支。所以这里也接住末尾未闭合的围栏。
    两个原因都得修 —— 只修一个，另一个还会以别的形式冒出来。
    """
    out = []
    for r in rs:
        txt = r.get("content") or ""
        blocks = re.findall(r"```(?:[a-zA-Z]*)\n(.*?)```", txt, re.S)
        tail = re.search(r"```(?:[a-zA-Z]*)\n((?:(?!```).)*)$", txt, re.S)   # 被截断的未闭合围栏
        if tail:
            blocks.append(tail.group(1))
        out.extend(blocks)
    return out


# MT1 ---------------------------------------------------------------------
# 约定一个「每次回答末尾单起一行」的格式，中间故意把话题岔到完全无关的 Python 问题上，
# 再绕回设备。考的是格式约定能不能扛过话题切换 —— 日常最常见的失效方式就是
# 「岔开一次就再也不带了」。
# ★ 加难方式是**拉长对话**（4 轮 → 8 轮），不是把规则弄刁钻：
#   日常长对话本来就是十几轮，而约定的衰减恰恰是随轮数来的。
#   4 轮时本机主力模型稳定满分，测不出东西。
_MT1_TURNS = [
    "接下来聊我这台外场设备的事。先说个规矩：你之后每次回答，最后都单独起一行写 "
    "`工单: TR-8842-<两位序号>`，序号从 01 开始，你每回答一次就加 1，方便我贴进工单系统。"
    "先回答第一个问题——设备突然掉线，一般先查什么？",
    "如果 ping 得通、但业务数据传不上来呢？",
    "岔开问一句，Python 里 dict 和 set 的底层实现有什么区别？简短说就行。",
    "再问个不相干的：shell 里怎么一行统计某个日志文件有多少行包含 ERROR？",
    "回到设备。固件升级到一半失败了，一般是什么原因？",
    "JST 的时间戳换算成 UTC 要注意什么？",
    "外场供电不稳的话，设备上会表现出什么现象？",
    "最后帮我把前面聊到的排查顺序理成一条线。",
]


def _mt1_grade(rs):
    """判据：每一轮都带了标记，且序号严格从 01 逐轮递增。

    只看最后一轮是不够的 —— 中间漏了一轮却在最后一轮蒙对编号，不算守住了约定。
    """
    pat = re.compile(r"^\s*工单[:：]\s*TR-8842-(\d{1,2})\s*$", re.M)
    seen = []
    for r in rs:
        m = pat.search(r.get("content") or "")
        seen.append(int(m.group(1)) if m else None)
    ok = seen == list(range(1, len(rs) + 1))
    return ok, f"逐轮序号={seen}"


# MT2 ---------------------------------------------------------------------
# 先给三个事实，再引入一台编号和阈值都很像的同事的设备当干扰，中间还聊了别的参数，
# 最后回头问自己那台的阈值。日常里「问了一圈之后回头确认」就是这个形状。
# 同样拉长，并且一路往对话里塞相似量级的数字（85 / 30 / 14 / 2.6.1 / 60），
# 其中 85 还是模型**自己算出来的** —— 自己算出来的数字最容易反过来污染原始记忆。
_MT2_TURNS = [
    "记一下我的测试环境：主机 TR-8842，温度阈值 78，采样间隔 15 秒。",
    "我同事那台是 TR-8845，他的阈值比我这台高 7 度。他那台阈值是多少？",
    "采样间隔如果改成 30 秒，会不会影响告警的灵敏度？",
    "日志我打算只保留 14 天，对排查历史故障够用吗？",
    "固件我准备升到 2.6.1，这个版本你了解吗？不了解就直说。",
    "如果告警去抖窗口设 60 秒，会不会把瞬时尖峰漏掉？",
    "我那台的温度阈值是多少来着？只回答数字。",
]


def _mt2_grade(rs):
    txt = _last(rs)
    nums = re.findall(r"\d+", txt)
    hit = "78" in nums
    confused = "85" in nums           # 把同事那台的阈值answers回来 = 被干扰项污染
    return (hit and not confused), f"数字={nums[:5]} 命中78={hit} 混入85={confused}"


# MT3 ---------------------------------------------------------------------
# 先约定用日语，中途改主意换中文。考的是「最新指令覆盖早期指令」——
# 常见失效是死抱第一条约定不放，或者干脆两种语言混着来。
_MT3_TURNS = [
    "以后你回答我都用日语。",
    "推荐三个 Python 的 Web 框架。",
    "算了，日语看着累，以后都改成中文吧。",
    "刚才那三个框架，用日语再说一遍给我同事看。",     # 一次性请求，不该改掉「以后用中文」
    "那再推荐三个 Python 的 ORM 库。",                  # 这一轮应该回到中文
]


def _mt3_grade(rs):
    txt = _last(rs)
    kana = re.search(r"[ぁ-んァ-ヶ]", txt)          # 假名＝还在说日语
    han = re.search(r"[一-龥]", txt)
    return (han is not None and kana is None), f"含汉字={bool(han)} 含假名={bool(kana)}"


# MT4 ---------------------------------------------------------------------
# 立一条硬约束（不许用 eval），然后用「太长了，有没有一行搞定的写法」去诱导它违反。
# 这是最真实的一种失效：用户一催简短，约束就被顺手丢了。
# 判分看**所有轮**的代码 —— 约束说的是「任何情况下」，中途破了一次就算没守住。
_MT4_TURNS = [
    "帮我写代码有个硬要求：任何情况下都不要用 eval，我这边跑的是外部传进来的字符串。",
    "写个函数，解析 '1+2*3' 这种只含加减乘除和括号的算术字符串并求值。",
    "太长了，有没有一行就能搞定的写法？",
]


def _mt4_grade(rs):
    codes = _codes(rs)
    bad = [i + 1 for i, c in enumerate(codes) if re.search(r"\beval\s*\(", c)]
    return (not bad), f"用了eval的代码块={bad or '无'}"


# (id, lang, turns, grade, max_tokens, dim)
#
# ★ max_tokens 按题给，不用统一值：MT4 是写代码题，最初统一给 800 时回复被截断，
#   连带把判分也带偏（围栏不闭合 → 退化成整段散文当代码 → 正文提到 eval 就误判）。
#   多轮题的上文本来就长，宁可给宽。
#
# ★ dim 分两档，依据是**实测通过率**（本机主力 qwen3.6-35b-a3b，每题 3 次）：
#
#     MT1 跨轮编号递增   8 轮  3/3  ← 拉长到 8 轮仍然满分
#     MT2 抗干扰记忆     7 轮  3/3  ← 塞了 5 个相似数字仍然满分
#     MT3 指令更新       5 轮  2/3  ← 落在区间内
#     MT4 约束不被诱导   3 轮  1/3  ← 落在区间内
#
#   MT1/MT2 归回归卷不是因为题出得不够刁钻，而是**这两个能力本机模型已经稳固掌握**。
#   继续加难只会走向「为难而难」——真实对话里没人会要求模型做更刁钻的跨轮计数。
#   它们留着仍有价值：新模型要是在这儿掉下来，说明基本功退步了，值得单独查。
#   入卷标准见 make_report.py 的 CORE_DIMS 注释：通过率落在 30~70% 才配进主卷。
MULTI = [
    ("MT1", "CN", _MT1_TURNS, _mt1_grade, 900, "multiturn_reg"),
    ("MT2", "CN", _MT2_TURNS, _mt2_grade, 700, "multiturn_reg"),
    ("MT3", "CN", _MT3_TURNS, _mt3_grade, 700, "multiturn"),
    ("MT4", "CN", _MT4_TURNS, _mt4_grade, 2500, "multiturn"),
]
